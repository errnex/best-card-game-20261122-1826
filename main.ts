// Ember Court — entrypoint (Node 22, standard library only).
// The game is plain static files under game/; this program copies game/ and
// screenshots/ beside this file into /output (or MAKEFUN_OUTPUT_DIR) and
// writes /output/dossier.json with the vendored make.fun library, so the
// sealed scorer can check the entry byte for byte. It runs twice in the
// grader and both runs must write identical bytes — it only copies files,
// so they do.
import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const repoRoot = fileURLToPath(new URL('.', import.meta.url));
const outputDir = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(outputDir, { recursive: true });
cpSync(join(repoRoot, 'game'), join(outputDir, 'game'), { recursive: true });
mkdirSync(join(outputDir, 'screenshots'), { recursive: true });
if (existsSync(join(repoRoot, 'screenshots'))) {
  cpSync(join(repoRoot, 'screenshots'), join(outputDir, 'screenshots'), { recursive: true });
}

// The scorer's caps, as the kit documents them: the dossier text cap shapes
// the bytes; the rest refuse an entry the scorer would refuse anyway.
const dossierText = buildDossier(outputDir, {
  text_max_bytes: 163840,
  screenshots: { max: 4, max_bytes: 262144 },
  game_max_files: 993,
  game_max_bytes: 50331648,
  game_path_max_bytes: 1000,
});
writeFileSync(join(outputDir, 'dossier.json'), dossierText);
